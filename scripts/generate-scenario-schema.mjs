// Generate TypeScript and the Go embedded schema from the shared JSON Schema.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const schema = JSON.parse(
  readFileSync(resolve(root, "schemas/scenario.schema.json"), "utf8"),
);
const q = JSON.stringify;
function type(s) {
  if (s === true || !s || Object.keys(s).length === 0) return "JSONValue";
  if (s === false) return "never";
  if (s.$ref) return s.$ref.split("/").at(-1);
  if (s.const !== undefined) return q(s.const);
  if (s.enum) return s.enum.map(q).join(" | ");
  if (s.oneOf || s.anyOf)
    return `(${(s.oneOf ?? s.anyOf).map(type).join(" | ")})`;
  if (s.allOf) return `(${s.allOf.map(type).join(" & ")})`;
  if (Array.isArray(s.type))
    return s.type.map((t) => type({ ...s, type: t })).join(" | ");
  if (s.type === "null") return "null";
  if (s.type === "boolean") return "boolean";
  if (["integer", "number"].includes(s.type))
    return s.minimum !== undefined && s.minimum === s.maximum
      ? q(s.minimum)
      : "number";
  if (s.type === "string") return "string";
  if (s.type === "array") {
    if (s.maxItems === 0) return "[]";
    return `Array<${type(s.items ?? true)}>`;
  }
  if (s.type === "object" || s.properties || s.additionalProperties) {
    const properties = Object.entries(s.properties ?? {});
    if (!properties.length)
      return `Record<string, ${s.additionalProperties === false ? "never" : type(s.additionalProperties ?? true)}>`;
    const required = new Set(s.required ?? []);
    return `{ ${properties.map(([name, value]) => `${q(name)}${required.has(name) ? "" : "?"}: ${type(value)};`).join(" ")} }`;
  }
  return "JSONValue";
}
const types =
  "// Generated by scripts/generate-scenario-schema.mjs. Do not edit.\n" +
  "export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };\n" +
  Object.entries(schema.definitions)
    .map(([name, value]) => `export type ${name} = ${type(value)};`)
    .join("\n") +
  `\nexport type ScenarioFile = ${type(schema)};\n`;
const artifacts = [
  [
    "go/internal/adapters/outbound/scenariocodec/scenario.schema.json",
    JSON.stringify(schema, null, 2) + "\n",
  ],
  ["apps/desktop/src/lib/generated/scenario-file.ts", types],
];
for (const [path, content] of artifacts) {
  const destination = resolve(root, path);
  if (check) {
    if (readFileSync(destination, "utf8") !== content)
      throw new Error(
        `${path} is stale; run npm run schema:generate in apps/desktop`,
      );
  } else writeFileSync(destination, content);
}
